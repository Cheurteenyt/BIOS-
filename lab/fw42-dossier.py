def dossier_pair(old, new):
    """The release-41 command: exam_pair + identify(new) + weld + score
    + novelty(new) + the pair coherence. Brand-new species are births
    that even the register universe cannot claim — the beyond-register
    event class."""
    f35, f37, f38, f39, f40, f41 = _mods()
    _install_walk_cache()
    _check_image(old)
    _check_image(new)
    examout, draft = f38.exam_pair(old, new)
    ident = f39.identify(new)
    merged, weld_report = f40.weld(draft, ident, lenses=None,
                                   target="release41")
    rows, n = f35.Oracle().score(merged)
    nov = f41.novelty(new, _universes())

    births = sorted(set(f37.Engine().inv(new)["modules"])
                    - set(f37.Engine().inv(old)["modules"]))
    deaths = sorted(set(f37.Engine().inv(old)["modules"])
                    - set(f37.Engine().inv(new)["modules"]))
    un_species = set(nov["species"].get("unregistered") or [])
    brand_new = sorted(set(births) & un_species)

    verdict = ident["verdict"]["verdict"]
    un_total = nov["summary"]["unregistered_total"]
    ic = identity_coupling(verdict, un_total)
    couples = coupling_rows(rows, _axis_entries(nov))
    refuses = []
    if ic == "refused-contradiction":
        refuses.append("L2/L3: the NEW image is byte-identical to a "
                       f"known release ({verdict}) yet carries "
                       f"{un_total} unregistered finding(s) — refusing.")
    if brand_new:
        coupling = "beyond-register-births"
    elif births or deaths:
        coupling = "registered-births"
    else:
        coupling = "clean-pair"
    profile = "refused" if refuses else (
        "clean-pair" if coupling == "clean-pair" else "event-pair")
    d = {
        "instrument": "fw42-dossier", "ring": RING,
        "mode": "dossier-pair", "old": old, "new": new,
        "target": "release41",
        "readings": {
            "oracle": {"instrument": "fw35-oracle", "ring": 35,
                       "counts": n,
                       "rows": [{"id": _pid(p), "verdict": v,
                                 "note": note} for p, v, note in rows]},
            "identity": {"instrument": "fw39-identity", "ring": 39,
                         "verdict": verdict,
                         "matched_release":
                             ident["verdict"].get("matched_release"),
                         "note": ident["verdict"].get("note")},
            "novelty": {"instrument": "fw41-novelty", "ring": 41,
                        "summary": nov["summary"]},
        },
        "pair_coherence": {
            "births": births, "deaths": deaths,
            "brand_new_species": brand_new,
            "coupling": coupling,
            "identity_coupling": ic,
            "coupling_rows": couples,
            "refusals": refuses,
            "profile": profile,
        },
        "weld_report": weld_report,
        "provenance": {"instrument": "fw42-dossier", "ring": RING,
                       "laws": ["L1 completeness", "L2 coherence",
                                "L3 calibration", "L4 separation"]},
    }
    return d, merged


