# -------------------------------------------------------------------- main

def main(argv=None):
    ap = argparse.ArgumentParser(prog="fw42-dossier")
    ap.add_argument("mode", choices=["dossier", "dossier-pair", "clean",
                                     "register", "selftest", "manifest"])
    ap.add_argument("args", nargs="*")
    ap.add_argument("--target", choices=["day0", "release41"],
                    default="day0")
    ap.add_argument("--lenses")
    ap.add_argument("--lens-wins", nargs="*", default=[])
    ap.add_argument("--out")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--no-live", action="store_true")
    a = ap.parse_args(argv)

    if a.mode == "manifest":
        return manifest()
    if a.mode == "selftest":
        return selftest(no_live=a.no_live)
    if a.mode == "register":
        show(load_register())
        return 0

    try:
        if a.mode == "dossier":
            if not a.args:
                print("dossier <image>", file=sys.stderr)
                return 2
            lenses = None
            if a.lenses:
                with open(a.lenses) as f:
                    lenses = json.load(f)
            d, merged = dossier(a.args[0], lenses=lenses, target=a.target,
                                lens_wins=a.lens_wins)
        elif a.mode == "dossier-pair":
            if len(a.args) < 2:
                print("dossier-pair <old> <new>", file=sys.stderr)
                return 2
            d, merged = dossier_pair(a.args[0], a.args[1])
        else:  # clean
            if not a.args:
                print("clean <rung>", file=sys.stderr)
                return 2
            d, merged = clean(a.args[0])
    except Refusal as e:
        print(f"REFUSAL: {e}", file=sys.stderr)
        return 2

    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            json.dump({"dossier": d, "findings": merged}, f, indent=2)
        print(f"written: {a.out}")
    if a.quiet:
        show_summary(d)
    else:
        show(d)
    return 0


if __name__ == "__main__":
    sys.exit(main())
