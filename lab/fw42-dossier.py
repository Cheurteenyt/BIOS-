# --------------------------------------------------- the walk memoization
# fw39._deep_inventory is deterministic and read-only; the exam/identify/
# novelty chain used to walk the SAME image up to three times per process
# (identify's fingerprint, fw41's _deep, the pair's ledger walks). fw42
# installs ONE pure memoization (abspath-keyed) on the fw39 module so
# every consumer shares a single walk per image. Gate I7 counts the
# walks to prove the weld saved the passes.

_WALKS = {}
_UNIVERSES = None


def _universes():
    """The register-derived detector universes, built ONCE per process
    (build_universes walks all nine rungs — 160 s measured; the selftest
    and the CLI share the cache). Pure: the universes depend on the
    registers and the corpus, never on the image under reading."""
    global _UNIVERSES
    if _UNIVERSES is None:
        _UNIVERSES = f41_mod().build_universes(build_smm=True)
    return _UNIVERSES


def _install_walk_cache():
    f39 = _mods()[3]
    orig = f39._deep_inventory
    if getattr(orig, "_fw42_memo", False):
        return
    def memoized(image):
        key = os.path.abspath(image)
        if key not in _WALKS:
            _WALKS[key] = orig(image)
        return _WALKS[key]
    memoized._fw42_memo = True
    memoized._orig = orig
    f39._deep_inventory = memoized


def walk_count():
    return len(_WALKS)


# ---------------------------------------------------------- the coherence

def _axis_entries(nov):
    """Unregistered-entry count per detector axis (the evidence a miss
    can be confirmed with)."""
    return {
        "species": len(nov["species"].get("unregistered") or []),
        "certs": len(nov["certs"].get("unregistered") or []),
        "dsdt": len(nov["dsdt"].get("unregistered") or []),
        "agesa": 1 if nov["agesa"].get("class") == "unregistered" else 0,
        "whitelist": (len(nov["whitelist"].get("extra") or [])
                      + len(nov["whitelist"].get("missing") or [])),
        "smm": len(nov["smm"].get("unregistered") or []),
    }


def identity_coupling(verdict, unregistered_total):
    """L2 for the judge x detector pair. known-release + unregistered
    content is impossible by the coverage proof (fw41 I1/I2) — a
    refusal, not a class to interpret."""
    if verdict == "known-release":
        if unregistered_total == 0:
            return "known-clean"
        return "refused-contradiction"
    if unregistered_total > 0:
        return "coherent-foreign"
    return "suspicious"


def _pid(p):
    """Oracle.score yields (prediction_dict, verdict, note) — accept both
    the dict and a bare id (the welded rows vs the raw rows)."""
    return p["id"] if isinstance(p, dict) else p


def coupling_rows(score_rows, entries):
    """L2: every oracle row gets its coupling class through the
    blind-spot map. hit -> aligned; na -> na; miss/partial -> blind,
    confirmed (detector has entries on the row's axis), bare (no
    entries), or identity (P-18 rides on identity_coupling)."""
    out = []
    for p, v, _note in score_rows:
        pid = _pid(p)
        axis, strength, _reason = AXIS_MAP[pid]
        if v == "hit":
            c = "aligned"
        elif v == "na":
            c = "na"
        elif strength == "identity":
            c = "identity"
        elif strength == "blind":
            c = "blind"
        elif entries.get(axis, 0) > 0:
            c = "confirmed"
        else:
            c = "bare"
        out.append({"id": pid, "verdict": v, "axis": axis,
                    "strength": strength, "coupling": c})
    return out


def profile_of(identity_c, refuses):
    """L2: the claim-free profile. Refusals dominate; the H3 question is
    NOT a profile (it is the P-18 row + the identity verdict)."""
    if refuses:
        return "refused"
    if identity_c == "known-clean":
        return "clean"
    if identity_c == "suspicious":
        return "suspicious"
    return "stranger"


# ------------------------------------------------------- the dossier itself

def _check_image(image):
    if not image or not os.path.exists(image):
        raise Refusal(f"image not found: {image!r} — L1 refuses to "
                      "assemble a dossier on a reading that cannot run")
    if not os.path.isfile(image):
        raise Refusal(f"not a file: {image!r}")


def _ceilings():
    path = os.path.join(HERE, "vendor-scorelines.json")
    with open(path) as f:
        return json.load(f).get("ceilings") or {}


def dossier(image, lenses=None, target="day0", geometry=True,
            lens_wins=()):
    """The ONE day-0 command: readings 1+2 (exam+identify+weld+score via
    the fw40 weld, identify run ONCE) + reading 3 (fw41 novelty on the
    same image) + the coherence layer. Returns the dossier dict."""
    f35, _f37, f38, f39, f40, f41 = _mods()
    _install_walk_cache()
    _check_image(image)
    fw_target = "day0-3644" if target == "day0" else "release-41"

    examout, draft = f38.exam(image, target=fw_target, geometry=geometry)
    ident = f39.identify(image)
    merged, weld_report = f40.weld(draft, ident, lenses=lenses,
                                   target=target, lens_wins=lens_wins)
    rows, n = f35.Oracle().score(merged)
    nov = f41.novelty(image, _universes())

    return _assemble(image, target, ident, nov, rows, n, merged,
                     weld_report, examout)


def _assemble(image, target, ident, nov, rows, n, merged, weld_report,
              examout=None):
    verdict = ident["verdict"]["verdict"]
    un_total = nov["summary"]["unregistered_total"]
    ic = identity_coupling(verdict, un_total)
    entries = _axis_entries(nov)
    couples = coupling_rows(rows, entries)
    refuses = []
    if ic == "refused-contradiction":
        refuses.append(
            "L2/L3: identity says known-release (byte-identity under the "
            "registered sha convention) but the detector found "
            f"{un_total} unregistered finding(s) — instrument "
            "disagreement on a known rung; registers drifted or an "
            "extractor broke. Refusing to profile.")
    # L3 calibration: byte-identity forces the scoreline onto the
    # ceiling registered for that rung (where the scorelines register
    # carries one).
    ceiling_note = None
    if verdict == "known-release" and not refuses:
        matched = ident["verdict"].get("matched_release")
        ceilings = _ceilings()
        if isinstance(matched, str) and matched in ceilings:
            c = ceilings[matched]["counts"]
            if (n["hit"], n["partial"], n["miss"], n["na"]) != (
                    c["hit"], c["partial"], c["miss"], c["na"]):
                refuses.append(
                    f"L3: byte-identical to {matched} but the scoreline "
                    f"{n} deviates from the registered ceiling {c} — "
                    "instrument disagreement, refusing to profile.")
            else:
                ceiling_note = f"scoreline == {matched} ceiling"
        elif isinstance(matched, list):
            ceiling_note = (f"sha matches {matched}; multiple rungs "
                            "share the body sha — no single ceiling")
        else:
            ceiling_note = (f"byte-identical to {matched}; no ceiling "
                            "registered for that rung (extension lives "
                            "in vendor-dossier-register.json)")
    profile = profile_of(ic, refuses)
    hits = sorted(_pid(p) for p, v, _ in rows if v == "hit")
    d = {
        "instrument": "fw42-dossier", "ring": RING,
        "mode": "dossier", "image": image, "target": target,
        "rom": {"bytes": (examout or {}).get("rom", {}).get("bytes")
                if isinstance((examout or {}).get("rom"), dict) else None},
        "readings": {
            "oracle": {"instrument": "fw35-oracle", "ring": 35,
                       "via": "fw40 weld (exam 38 + identify 39)",
                       "counts": n,
                       "rows": [{"id": _pid(p), "verdict": v,
                                 "note": note} for p, v, note in rows]},
            "identity": {"instrument": "fw39-identity", "ring": 39,
                         "verdict": verdict,
                         "matched_release":
                             ident["verdict"].get("matched_release"),
                         "nearest_release":
                             ident["verdict"].get("nearest_release"),
                         "distinct_fingerprints_count":
                             ident["verdict"].get(
                                 "distinct_fingerprints_count"),
                         "note": ident["verdict"].get("note")},
            "novelty": {"instrument": "fw41-novelty", "ring": 41,
                        "summary": nov["summary"],
                        "axes": {ax: {k: nov[ax].get(k)
                                      for k in _NOVELTY_KEYS[ax]}
                                 for ax in f41_mod().AXES}},
        },
        "coherence": {
            "identity_coupling": ic,
            "coupling_rows": couples,
            "axis_entries": entries,
            "unregistered_total": un_total,
            "hit_set": hits,
            "refusals": refuses,
            "ceiling_note": ceiling_note,
            "profile": profile,
        },
        "weld_report": weld_report,
        "provenance": {"instrument": "fw42-dossier", "ring": RING,
                       "laws": ["L1 completeness", "L2 coherence",
                                "L3 calibration", "L4 separation"],
                       "readings": ["fw35+fw38+fw39+fw40 (welded)",
                                    "fw39-identity", "fw41-novelty"]},
    }
    return d, merged


