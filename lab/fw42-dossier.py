def _load_mod(name):
    key = f"_{name}"
    if key not in _M:
        path = os.path.join(HERE, name + ".py")
        spec = importlib.util.spec_from_file_location(name, path)
        m = importlib.util.module_from_spec(spec)
        sys.modules[name] = m
        spec.loader.exec_module(m)
        _M[key] = m
    return _M[key]


def _mods():
    """(fw35, fw37, fw38, fw39, fw40, fw41) — the whole chain. fw42 sits
    on top, never instead."""
    return (_load_mod("fw35-oracle"), _load_mod("fw37-differ"),
            _load_mod("fw38-exam"), _load_mod("fw39-identity"),
            _load_mod("fw40-merge"), _load_mod("fw41-novelty"))


